
import streamlit as st
import pandas as pd
import joblib

# Page configuration
st.set_page_config(
    page_title="Heart Disease Risk Prediction",
    page_icon="❤️",
    layout="centered"
)

# Load saved ML files
model = joblib.load("heart_disease_model.pkl")
scaler = joblib.load("scaler.pkl")
features = joblib.load("feature_names.pkl")

# App title
st.title("❤️ Heart Disease Risk Prediction")
st.write("Enter patient details to get a machine learning prediction.")

st.info(
    "This application is an educational project. "
    "It is not a medical diagnosis tool."
)

# Patient input form
with st.form("patient_form"):

    st.subheader("Patient Information")

    age = st.number_input("Age", min_value=1, max_value=120, value=45)

    sex = st.selectbox("Sex", ["Male", "Female"])

    st.subheader("Health Measurements")

    systolic = st.number_input(
        "Resting Systolic Blood Pressure", min_value=0.0, value=120.0
    )

    diastolic = st.number_input(
        "Resting Diastolic Blood Pressure", min_value=0.0, value=80.0
    )

    cholesterol = st.number_input(
        "Total Cholesterol", min_value=0.0, value=190.0
    )

    hdl = st.number_input("HDL", min_value=0.0, value=50.0)

    ldl = st.number_input("LDL", min_value=0.0, value=110.0)

    triglycerides = st.number_input(
        "Triglycerides", min_value=0.0, value=130.0
    )

    fasting_sugar = st.number_input(
        "Fasting Blood Sugar", min_value=0.0, value=95.0
    )

    family_history = st.selectbox(
        "Family History of Heart Disease", ["No", "Yes"]
    )

    submit = st.form_submit_button("Predict")

# Prediction
if submit:

    patient_data = {
        "age": age,
        "resting_bp_systolic": systolic,
        "resting_bp_diastolic": diastolic,
        "cholesterol_total": cholesterol,
        "hdl": hdl,
        "ldl": ldl,
        "triglycerides": triglycerides,
        "fasting_blood_sugar": fasting_sugar,
        "sex_Male": 1 if sex == "Male" else 0,
        "family_history_True": 1 if family_history == "Yes" else 0
    }

    patient_df = pd.DataFrame([patient_data])
    patient_df = patient_df[features]

    patient_scaled = scaler.transform(patient_df)

    prediction = model.predict(patient_scaled)

    st.subheader("Prediction Result")

    if prediction[0] == 1:
        st.error("Model Prediction: Heart Disease Detected")
    else:
        st.success("Model Prediction: No Heart Disease Detected")

    st.warning(
        "This result is generated by a machine learning model "
        "and must not be used for medical decisions."
    )
